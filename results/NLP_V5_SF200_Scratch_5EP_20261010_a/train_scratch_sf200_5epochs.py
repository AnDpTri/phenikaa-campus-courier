# One epoch = 200K synthetic generated by exact task weights, interleaved.
# Each new sentence globally deduplicated against ALL prior scratch epochs.
grammar_bad=re.compile(r"\b(khu vuc khu|dia diem diem|dia diem vi tri|buu kien buu kien|ngoai kien buu kien|ke do moi dia chi|sau do can dia chi|tai tai|o o)\b")
def spec_dict(spec):
    return None if spec is None else {"type":spec.type,"ref":spec.ref,"anchor":spec.anchor}

def make_epoch(seed_i,epoch_no):
    gen_seed=2026110500+1000*seed_i+epoch_no
    data=RUN/f"scratch_s{seed_i}_e{epoch_no:02d}_seed{gen_seed}.jsonl"
    provenance=RUN/f"scratch_s{seed_i}_e{epoch_no:02d}_roles.jsonl"
    manifest=RUN/f"scratch_s{seed_i}_e{epoch_no:02d}_manifest.json"
    for path in (data,provenance,manifest):
        if path.exists():raise FileExistsError("Refuse existing data: "+str(path))
    g=G.Generator(seed=gen_seed,holdout=False,mode="weighted")
    seq=tuple(G.WEIGHTED_RECIPES)
    credits={k:0 for k in seq}
    counts=collections.Counter()
    rejection=collections.Counter()
    opening=collections.Counter()
    rows=[]
    start=time.time()
    with data.open("x",encoding="utf-8",newline="\n") as stream,provenance.open("x",encoding="utf-8",newline="\n") as roles:
        for i in range(N):
            for k in seq:credits[k]+=G.WEIGHTED_RECIPES[k]
            recipe=max(seq,key=lambda k:(credits[k],-seq.index(k)))
            credits[recipe]-=100
            g._forced_recipe=recipe
            for attempt in range(1000):
                e=g.example()
                t=fold(e.text).strip()
                digest=text_hash(e.text)
                first=" ".join(t.split()[:8])
                length=len(tokenize(e.text))
                if length<8 or length>MAX_TOKENS:rejection["token_length"]+=1;continue
                if digest in seen:rejection["duplicate"]+=1;continue
                if opening[first]>=35:rejection["repeat_opening"]+=1;continue
                if grammar_bad.search(t):rejection["known_grammar"]+=1;continue
                role=g.last_provenance
                if recipe!="v2_general":
                    if e.urgent and not any(fold(x) in t for x in G.URGENT_POS):raise RuntimeError("urgent evidence")
                    if e.fragile and not any(fold(x) in t for x in G.FRAGILE_POS):raise RuntimeError("fragile evidence")
                    for old in ("former_destination","former_pickup"):
                        if role[old] is not None and fold(role[old]) not in t:
                            raise RuntimeError(old)
                    for neg in role["negative_roles"]:
                        if fold(neg["text"]) not in t:raise RuntimeError("missing negative role")
                    if e.goal.ref=="anchor_near" and not any(q in t for q in ("khong tinh","loai tru","ngoai","khong ke","tru moc")):
                        raise RuntimeError("ambiguous anchor exclusion")
                assert len(spec_labels(e.goal,e.via,e.urgent,e.fragile))==8
                seen.add(digest)
                opening[first]+=1
                counts[recipe]+=1
                counts["via"]+=e.via is not None
                counts["accented"]+=any(ord(c)>127 for c in e.text)
                rows.append((e.text,e.goal,e.via,e.urgent,e.fragile))
                out={"id":f"sf200_s{seed_i}_e{epoch_no:02d}_{i+1:06d}",
                     "text":e.text,"goal":spec_dict(e.goal),
                     "via":spec_dict(e.via),"urgent":e.urgent,"fragile":e.fragile}
                stream.write(json.dumps(out,ensure_ascii=False,separators=(",",":"))+"\n")
                roles.write(json.dumps({"id":out["id"],"recipe":recipe,**role},
                          ensure_ascii=False,separators=(",",":"))+"\n")
                break
            else:
                raise RuntimeError(f"Too many rejects at seed={seed_i}, epoch={epoch_no}, row={i}")
            if (i+1)%25000==0:
                event("GEN_PROGRESS",seed_index=seed_i,epoch=epoch_no,
                      generated=i+1,total=N,quota=dict((k,counts[k]) for k in seq),
                      rejects=dict(rejection),elapsed_s=round(time.time()-start,1))
    for k in seq:
        assert counts[k]==N*G.WEIGHTED_RECIPES[k]//100,(k,counts[k])
    assert max(opening.values())<=35
    digest=sha_file(data)
    info={"seed_index":seed_i,"epoch":epoch_no,"data_seed":gen_seed,
          "rows":len(rows),"weighted_quotas":{k:counts[k] for k in seq},
          "stats":dict(counts),"rejects":dict(rejection),
          "unique_first8":len(opening),"max_first8_repeat":max(opening.values()),
          "sha256":digest,"data_file":str(data),
          "roles_file":str(provenance),"elapsed_s":round(time.time()-start,1)}
    with manifest.open("x",encoding="utf-8") as f:json.dump(info,f,ensure_ascii=False,indent=2)
    event("GEN_COMPLETE",**info)
    return rows,info

@torch.no_grad()
def assess(model,rows,batch=128):
    model.eval()
    cross=collections.Counter()
    correct=collections.Counter()
    n=0
    predictions=[]
    parser=NeuralMissionParser(model)
    for off in range(0,len(rows),batch):
        part=rows[off:off+batch]
        x=encode_texts([r[0] for r in part]).to(DEVICE)
        labs=[spec_labels(r[1],r[2],r[3],r[4]) for r in part]
        logits=model(x)
        for head in HEADS:
            target=torch.tensor([a[head] for a in labs],device=DEVICE)
            cross[head]+=float(nn.functional.cross_entropy(logits[head],target,reduction="sum").item())
            correct[head]+=int((logits[head].argmax(dim=1)==target).sum().item())
        predictions.extend(p.parsed for p in parser.predict_batch([r[0] for r in part]))
        n+=len(part)
    counts=collections.Counter()
    absence=0
    false_present=0
    missed=0
    present=0
    for row,pred in zip(rows,predictions):
        check={"goal":pred.goal==row[1],"via":pred.via==row[2],
               "urgent":pred.urgent==row[3],"fragile":pred.fragile==row[4]}
        for k,v in check.items():counts[k]+=v
        counts["all"]+=all(check.values())
        if row[2] is None:
            absence+=1;false_present+=pred.via is not None
        else:
            present+=1;missed+=pred.via is None
    return {"n":n,"sum_loss":sum(cross.values())/n,
            "loss_by_head":{k:cross[k]/n for k in HEADS},
            "accuracy_by_head":{k:correct[k]/n for k in HEADS},
            "exact":{k:counts[k]/n for k in ("goal","via","urgent","fragile","all")},
            "via_none_count":absence,"via_fpr":false_present/absence if absence else None,
            "via_present_count":present,"via_miss_rate":missed/present if present else None}

def checkpoint_path(seed_i,epoch):
    return RUN/f"scratch_s{seed_i}_epoch{epoch:02d}.pt"

def train_seed(seed_i,model_seed):
    random.seed(model_seed);torch.manual_seed(model_seed);torch.cuda.manual_seed_all(model_seed)
    net=NeuralParserNet(dim=CFG["dim"],hidden=CFG["hidden"]).to(DEVICE)
    optimizer=torch.optim.AdamW(net.parameters(),lr=CFG["peak_lr"],weight_decay=CFG["weight_decay"])
    rows_per_epoch=N+len(REAL)*CFG["real_train_repeat"]
    updates=math.ceil(rows_per_epoch/CFG["effective_batch"])
    total_steps=CFG["epochs_per_seed"]*updates
    schedule=torch.optim.lr_scheduler.OneCycleLR(
        optimizer,max_lr=CFG["peak_lr"],total_steps=total_steps,
        pct_start=CFG["onecycle_warmup_pct"],anneal_strategy="cos")
    event("SEED_START",seed_index=seed_i,model_seed=model_seed,
          parameters=sum(p.numel() for p in net.parameters()),
          update_steps_epoch=updates,total_updates=total_steps,
          init="random_from_scratch",official_validation_loaded=False)
    previous_diag=None;loss_worsens=0
    seed_diagnostics=[]
    for epoch in range(1,CFG["epochs_per_seed"]+1):
        synthetic,manifest=make_epoch(seed_i,epoch)
        # Sample SEEN training rows for memorization diagnostic; not for selection.
        sample_rng=random.Random(model_seed*1000+epoch)
        probe_train=[synthetic[i] for i in sample_rng.sample(range(N),k=512)]
        rows=synthetic+REAL*CFG["real_train_repeat"]
        del synthetic
        random.Random(model_seed*1000+epoch).shuffle(rows)
        net.train()
        running_loss=0.0;cum=collections.Counter();hits=collections.Counter()
        done=0;updates_done=0
        start=time.time()
        optimizer.zero_grad(set_to_none=True)
        for start_i in range(0,len(rows),CFG["batch_micro"]):
            chunk=rows[start_i:start_i+CFG["batch_micro"]]
            x=encode_texts([r[0] for r in chunk]).to(DEVICE)
            labels=[spec_labels(r[1],r[2],r[3],r[4]) for r in chunk]
            y={h:torch.tensor([lab[h] for lab in labels],device=DEVICE) for h in HEADS}
            pred=net(x)
            each={h:nn.functional.cross_entropy(pred[h],y[h]) for h in HEADS}
            loss=sum(each.values())
            if not torch.isfinite(loss):raise RuntimeError("NaN or infinity in training loss")
            (loss/CFG["grad_accumulation"]).backward()
            for h in HEADS:
                cum[h]+=float(each[h].item())*len(chunk)
                hits[h]+=int((pred[h].argmax(dim=1)==y[h]).sum().item())
            running_loss+=float(loss.item())*len(chunk)
            done+=len(chunk)
            # Two micro batches simulate effective batch 128.
            mb=(start_i//CFG["batch_micro"])+1
            if mb%CFG["grad_accumulation"]==0 or done==len(rows):
                nn.utils.clip_grad_norm_(net.parameters(),CFG["gradient_clip"])
                optimizer.step();schedule.step()
                optimizer.zero_grad(set_to_none=True)
                updates_done+=1
                if (updates_done%CFG["live_log_every_optimizer_steps"]==0 or
                    updates_done==1 or updates_done==updates):
                    info={"seed_index":seed_i,"epoch":epoch,
                          "updates":updates_done,"updates_per_epoch":updates,
                          "rows_seen":done,"rows_epoch":len(rows),
                          "mean_train_loss":running_loss/done,
                          "train_loss_by_head":{h:cum[h]/done for h in HEADS},
                          "train_acc_by_head":{h:hits[h]/done for h in HEADS},
                          "lr":optimizer.param_groups[0]["lr"],
                          "gpu_reserved_mib":round(torch.cuda.memory_reserved()/1048576),
                          "gpu_max_reserved_mib":round(torch.cuda.max_memory_reserved()/1048576),
                          "elapsed_s":round(time.time()-start,1)}
                    event("TRAIN_PROGRESS",**info)
        assert updates_done==updates and done==rows_per_epoch,(done,updates_done)
        del rows
        gc.collect()
        train_diag=assess(net,probe_train,batch=96)
        diagnostics={}
        for name,probe in PROBES.items():
            diagnostics[name]=assess(net,probe,batch=96)
        holdout_score=sum(diagnostics[k]["sum_loss"]*len(PROBES[k]) for k in PROBES)/sum(map(len,PROBES.values()))
        loss_gap=holdout_score-train_diag["sum_loss"]
        # DIAGNOSTIC WARNINGS ONLY; never select or stop checkpoint based on these.
        bad=False
        if previous_diag is not None and holdout_score>previous_diag["loss"]+0.025:
            loss_worsens+=1
        else:
            loss_worsens=0
        if loss_worsens>=2:bad=True
        overfit={
            "synthetic_holdout_mean_loss":holdout_score,
            "seen_train_probe_loss":train_diag["sum_loss"],
            "holdout_minus_seen_gap":loss_gap,
            "consecutive_worsening_holdout_loss":loss_worsens,
            "overfit_warning":bad,
            "note":"Synthetic phrase-bank holdout only, may share template families. No official validation accessed. This is DIAGNOSTIC ONLY."
        }
        previous_diag={"loss":holdout_score}
        ckpt=checkpoint_path(seed_i,epoch)
        if ckpt.exists():raise FileExistsError("Refuse old checkpoint "+str(ckpt))
        # .save path receives an exclusive newly opened binary handle.
        with ckpt.open("xb") as f:
            torch.save({
                "kind":"courier.nlp.neural_parser","config":net.config,
                "state_dicts":[{k:v.detach().cpu() for k,v in net.state_dict().items()}],
                "checkpoint":True,"seed":model_seed,"epoch":epoch,
                "experiment":CFG["name"],
                "training":{"from_scratch":True,"official_validation_used":False},
                "synthetic_seed":manifest["data_seed"],"model_config":net.config,
            },f)
        summary={"seed_index":seed_i,"model_seed":model_seed,"epoch":epoch,
                 "train_loss":running_loss/done,
                 "train_loss_by_head":{h:cum[h]/done for h in HEADS},
                 "train_acc_by_head":{h:hits[h]/done for h in HEADS},
                 "lr_end":optimizer.param_groups[0]["lr"],
                 "training_wall_seconds":round(time.time()-start,1),
                 "train_seen_probe":train_diag,
                 "synthetic_heldout":diagnostics,
                 "overfit":overfit,"checkpoint":str(ckpt),
                 "data_manifest":str(RUN/f"scratch_s{seed_i}_e{epoch:02d}_manifest.json")}
        seed_diagnostics.append(summary)
        event("EPOCH_COMPLETE",**summary)
        if bad:
            event("OVERFIT_WARNING",seed_index=seed_i,epoch=epoch,
                  holdout_loss=holdout_score,train_probe_loss=train_diag["sum_loss"],
                  reason="synthetic diagnostic holdout loss worsened for 2 successive epochs")
        event("CHECKPOINT_SAVED",seed_index=seed_i,epoch=epoch,
              checkpoint=str(ckpt),selection_policy="precommitted epoch05")
        del probe_train
        gc.collect()
    assert len(seed_diagnostics)==5
    event("SEED_COMPLETE",seed_index=seed_i,model_seed=model_seed,
          selected_epoch=5,checkpoint=str(checkpoint_path(seed_i,5)),
          policy="FIXED_LAST_EPOCH_NO_VALIDATION_SELECTION")
    del net,optimizer,schedule
    torch.cuda.empty_cache()
    return seed_diagnostics

with METRICS.open("x",encoding="utf-8",newline="\n") as events:
    event("RUN_START",name=CFG["name"],device=str(DEVICE),
          gpu=torch.cuda.get_device_name(0),dataset="official_train ONLY",
          real_train_n=len(REAL),synthetic_per_epoch=N,models=MODELS,
          total_epochs=len(MODELS)*CFG["epochs_per_seed"],
          synthetic_generator_sha256=CFG["generator_sha256"],
          validation_used=False,selection="precommitted 5th epoch for each seed")
    results={}
    for i,seed in enumerate(MODELS):
        results[str(seed)]=train_seed(i,seed)
    # Assemble ensemble from exactly three PRECOMMITTED last-epoch checkpoints.
    nets=[]
    for i,seed in enumerate(MODELS):
        art=torch.load(checkpoint_path(i,15),map_location="cpu",weights_only=False)
        assert art["config"]=={"dim":96,"hidden":192}
        model=NeuralParserNet(dim=96,hidden=192)
        model.load_state_dict(art["state_dicts"][0])
        nets.append(model.cpu().eval())
    if ENSEMBLE.exists():raise FileExistsError("Refuse overwrite ensemble")
    with ENSEMBLE.open("xb") as f:
        torch.save({
            "kind":"courier.nlp.neural_parser",
            "config":{"dim":96,"hidden":192},
            "state_dicts":[{k:v.detach().cpu() for k,v in net.state_dict().items()} for net in nets],
            "experiment":CFG["name"],"model_seed":MODELS,
            "checkpoint_selection":"epoch05 fixed, no official validation",
            "training":{"from_scratch":True,"data":"train+fresh synthetic only",
                        "generator_sha256":CFG["generator_sha256"]},
        },f)
    report={"status":"DONE","experiment":CFG["name"],"seeds":MODELS,
            "epochs_per_seed":CFG["epochs_per_seed"],
            "synthetic_examples_per_epoch":N,
            "replayed_training_samples_per_epoch":len(REAL)*CFG["real_train_repeat"],
            "ensemble_checkpoint":str(ENSEMBLE),
            "model_seed_final_checkpoints":[str(checkpoint_path(i,15)) for i in range(3)],
            "epoch_diagnostics":results,
            "critical_limitations":[
                "Never loaded official validation or test; synthetic diagnostic holdouts monitored but NOT used for checkpoint selection.",
                "Synthetic probes may share sentence-template families with the generator; overfit flags are diagnostic, not a proof of generalization.",
                "Fixed epoch 5 checkpoints can underperform an earlier epoch; deliberately avoid retrospective model selection bias.",
                "An independent blind natural-language evaluation is required to compare generalization."
            ]}
    with FINAL.open("x",encoding="utf-8") as f:json.dump(report,f,ensure_ascii=False,indent=2)
    event("RUN_COMPLETE",ensemble=str(ENSEMBLE),report=str(FINAL))
