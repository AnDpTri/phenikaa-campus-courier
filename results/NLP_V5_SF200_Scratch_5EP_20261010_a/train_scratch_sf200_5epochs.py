"""V5-SF200-Scratch: from-zero, 3-seed, 5-epoch, fresh 200K per epoch.

Strong isolation:
* Official validation and test are NEVER loaded.
* Checkpoints are saved each epoch with a PRECOMMITTED epoch-15 selection.
* Fixed train-bank/heldout-bank synthetic probes are DIAGNOSTIC ONLY.
* All outputs are created exclusively inside NEW results path.
* Source and checkpoints from V2/V4/V5 are used neither for initialization
  nor modified. The frozen generator is the exact V5-SF200 version.
"""
