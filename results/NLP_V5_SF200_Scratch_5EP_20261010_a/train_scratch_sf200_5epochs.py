def event(kind,**fields):
    entry={"event":kind,"time_unix":round(time.time(),3),**fields}
    line=json.dumps(entry,ensure_ascii=False)
    # JSONL and stdout are newly created within this run.
    events.write(line+"\n")
    events.flush()
    print(kind,line,flush=True)

def text_hash(text):
    return hashlib.blake2b(fold(text).strip().encode("utf-8"),digest_size=8).digest()

# Exclude both existing V5-SF200 data epochs from the fresh scratch training.
seen=set()
for path in (
    ROOT/"results/NLP_V4_R2/unified_weighted_200k_20261010_a/train_weighted_unified_200000_seed2026101060.jsonl",
    ROOT/"results/NLP_V5_SemanticFusion_200K/sf200_epoch2_seed2026101061.jsonl",
):
    with path.open(encoding="utf-8") as stream:
        for line in stream:seen.add(text_hash(json.loads(line)["text"]))
    print("REF_EXCLUSION_READY",path.name,len(seen),flush=True)

